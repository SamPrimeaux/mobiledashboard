THEME_HELPER = r"""
// AGENT_MEAUXBILITY_THEME_CSS_HELPER_START
function agentMeauxbilitySafeJson(raw, fallback = {}) {
  if (!raw || typeof raw !== 'string') return fallback;
  try {
    const parsed = JSON.parse(raw);
    return parsed && typeof parsed === 'object' ? parsed : fallback;
  } catch (_) {
    return fallback;
  }
}

function agentMeauxbilityCssVarName(key) {
  const clean = String(key || '')
    .replace(/[A-Z]/g, m => '-' + m.toLowerCase())
    .replace(/[^a-z0-9_-]/gi, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
  return clean.startsWith('--') ? clean : `--${clean}`;
}

function agentMeauxbilityCssVarsFromObject(obj, prefix = '') {
  const lines = [];
  for (const [key, value] of Object.entries(obj || {})) {
    if (value === null || value === undefined) continue;
    if (typeof value === 'object') continue;
    const name = agentMeauxbilityCssVarName(prefix ? `${prefix}-${key}` : key);
    const val = String(value).replace(/[;{}]/g, '');
    lines.push(`  ${name}: ${val};`);
  }
  return lines.join('\n');
}

function agentMeauxbilityThemeImport(cssUrl, mode = 'vars') {
  if (mode !== 'full') return '';
  if (!cssUrl || typeof cssUrl !== 'string') return '';
  const safe = cssUrl.trim();
  if (!safe.startsWith('https://assets.inneranimalmedia.com/')) return '';
  return `@import url("${safe}");\n\n`;
}

async function handleAgentMeauxbilityThemeCss(request, env) {
  const url = new URL(request.url);
  const slug = url.searchParams.get('slug') || 'moon-glass';
  const mode = url.searchParams.get('mode') || 'vars';

  let theme = null;
  let warning = '';

  try {
    if (env.DB) {
      theme = await env.DB.prepare(`
        SELECT
          name,
          slug,
          css_url,
          css_vars_json,
          tokens_json,
          brand_json,
          layout_json,
          typography_json,
          components_json,
          motion_json,
          updated_at
        FROM cms_themes
        WHERE slug = ?
          AND status = 'active'
        LIMIT 1
      `).bind(slug).first();
    } else {
      warning = 'missing DB binding';
    }
  } catch (err) {
    warning = err && err.message ? err.message : String(err);
  }

  const cssVars = agentMeauxbilitySafeJson(theme && theme.css_vars_json, {});
  const tokens = agentMeauxbilitySafeJson(theme && theme.tokens_json, {});
  const brand = agentMeauxbilitySafeJson(theme && theme.brand_json, {});
  const layout = agentMeauxbilitySafeJson(theme && theme.layout_json, {});
  const typography = agentMeauxbilitySafeJson(theme && theme.typography_json, {});
  const components = agentMeauxbilitySafeJson(theme && theme.components_json, {});

  const css = `${agentMeauxbilityThemeImport(theme && theme.css_url, mode)}
/*
  Agent Meauxbility runtime CMS theme
  slug: ${theme && theme.slug ? theme.slug : slug}
  name: ${theme && theme.name ? theme.name : 'fallback'}
  updated_at: ${theme && theme.updated_at ? theme.updated_at : 'n/a'}
  warning: ${warning || 'none'}
*/
:root {
${agentMeauxbilityCssVarsFromObject(cssVars)}
${agentMeauxbilityCssVarsFromObject(tokens, 'theme')}
${agentMeauxbilityCssVarsFromObject(brand, 'brand')}
${agentMeauxbilityCssVarsFromObject(layout, 'layout')}
${agentMeauxbilityCssVarsFromObject(typography, 'typography')}
${agentMeauxbilityCssVarsFromObject(components, 'component')}
}
`;

  return new Response(css, {
    status: 200,
    headers: {
      'content-type': 'text/css;charset=UTF-8',
      'cache-control': 'no-store'
    }
  });
}
// AGENT_MEAUXBILITY_THEME_CSS_HELPER_END
""".strip()


def now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%fZ")


def stamp() -> str:
    return datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")


def run(cmd: list[str], *, check: bool = True, input_text: str | None = None) -> subprocess.CompletedProcess[str]:
    print("+", " ".join(cmd))
    proc = subprocess.run(cmd, cwd=ROOT, text=True, input=input_text, capture_output=True)
    if proc.stdout:
        print(proc.stdout.rstrip())
    if proc.stderr:
        print(proc.stderr.rstrip(), file=sys.stderr)
    if check and proc.returncode != 0:
        raise SystemExit(f"command failed ({proc.returncode}): {' '.join(cmd)}")
    return proc


def backup(path: Path) -> None:
    if path.exists():
        dst = path.with_suffix(path.suffix + ".backup.moon-glass." + stamp())
        shutil.copy2(path, dst)
        print(f"backup -> {dst}")



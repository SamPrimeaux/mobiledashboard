#!/usr/bin/env python3
"""
part5_moon_glass_cms_full_install.py

One-file install for the new Moon Glass CMS baseline.

What this does:
  1. Creates reusable Moon Glass theme artifacts:
       public/themes/moon-glass/theme.css
       public/themes/moon-glass/theme.json

  2. Creates a new Shopify-quality CMS editor shell:
       public/cms/moon-glass-editor.html
       src/generated/moon-glass-cms-editor-html.js

  3. Patches worker.js:
       - imports MOON_GLASS_CMS_EDITOR_HTML
       - serves /cms and /cms/ from the new Moon Glass editor shell
       - installs/updates /api/cms/theme.css runtime endpoint
       - keeps mode=vars and mode=full support

  4. If env is loaded, installs the theme:
       - uploads theme.css to R2 production bucket from CLOUDFLARE_R2_BUCKET
         fallback: inneranimalmedia
       - upserts cms_themes slug=moon-glass into D1 IAM_D1_DB
       - verifies the D1 row

  5. Optionally deploys the Worker:
       default: deploy enabled unless --no-deploy is passed

Required before running:
  source scripts/cms/load-agent-meauxbility-env.sh
  export CLOUDFLARE_API_TOKEN="$AGENT_DASHBOARD_API_TOKEN"

Safe properties:
  - Makes backups before patching worker.js.
  - Does not delete existing CMS snapshot.
  - Does not remove existing themes.
  - Upserts only slug='moon-glass'.
"""


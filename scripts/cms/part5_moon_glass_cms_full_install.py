def strip_between(text: str, start: str, end: str) -> str:
    return re.sub(re.escape(start) + r".*?" + re.escape(end), "", text, flags=re.S)


def insert_import(worker: str) -> str:
    if IMPORT_LINE in worker:
        return worker

    if worker.lstrip().startswith("import "):
        return IMPORT_LINE + "\n" + worker

    return IMPORT_LINE + "\n" + worker


def insert_after_url(worker: str, block: str) -> str:
    patterns = [
        r"(const\s+url\s*=\s*new\s+URL\s*\(\s*request\.url\s*\)\s*;)",
        r"(let\s+url\s*=\s*new\s+URL\s*\(\s*request\.url\s*\)\s*;)",
        r"(var\s+url\s*=\s*new\s+URL\s*\(\s*request\.url\s*\)\s*;)",
    ]
    for pattern in patterns:
        m = re.search(pattern, worker)
        if m:
            return worker[:m.end()] + "\n" + block + worker[m.end():]
    raise SystemExit("Could not find new URL(request.url) insertion point in worker.js")


def patch_worker() -> None:
    if not WORKER.exists():
        raise SystemExit("worker.js not found")

    backup(WORKER)
    worker = WORKER.read_text(errors="replace")

    worker = insert_import(worker)

    worker = strip_between(worker, CMS_ROUTE_START, CMS_ROUTE_END)
    worker = strip_between(worker, THEME_ROUTE_START, THEME_ROUTE_END)
    worker = strip_between(worker, THEME_HELPER_START, THEME_HELPER_END)

    # If the older CMS route block exists, remove it so /cms uses Moon Glass.
    worker = strip_between(worker, "// AGENT_MEAUXBILITY_CMS_ROUTE_START", "// AGENT_MEAUXBILITY_CMS_ROUTE_END")

    worker = insert_after_url(worker, THEME_ROUTE_BLOCK + "\n" + CMS_ROUTE_BLOCK)

    worker = worker.rstrip() + "\n\n" + THEME_HELPER + "\n"

    WORKER.write_text(worker)
    print(f"patched -> {WORKER}")


